"""Report source schemas and counts without reading connection column buffers."""

import json
from pathlib import Path
import struct
import sys

import pyarrow as pa
import pyarrow.compute as pc
import pyarrow.feather as feather
import pyarrow.ipc as ipc

DATA_DIR = Path(__file__).resolve().parent


def field_offset(metadata: bytes, table: int, field: int) -> int:
    """Locate a FlatBuffers field; omitted scalar fields have their zero default."""
    vtable = table - struct.unpack_from('<i', metadata, table)[0]
    entry = 4 + 2 * field
    if entry >= struct.unpack_from('<H', metadata, vtable)[0]:
        return 0
    offset = struct.unpack_from('<H', metadata, vtable + entry)[0]
    return table + offset if offset else 0


def batch_row_counts(path: Path) -> list[int]:
    """Read IPC Message / RecordBatch metadata, seeking past every data body.

    Layout: https://arrow.apache.org/docs/format/Columnar.html#ipc-file-format
    Message.fbs: version, header_type, header, bodyLength.
    Message.fbs also defines RecordBatch: length is the first field.
    """
    counts = []
    with path.open('rb') as source:
        if source.read(6) != b'ARROW1':
            raise ValueError(f'{path.name}: not an Arrow IPC file')
        source.seek(8)
        while True:
            prefix = source.read(4)
            if len(prefix) != 4:
                raise ValueError('Truncated IPC message prefix')
            size = struct.unpack('<I', prefix)[0]
            if size == 0xFFFFFFFF:
                size = struct.unpack('<I', source.read(4))[0]
            if size == 0:
                break
            metadata = source.read(size)
            if len(metadata) != size:
                raise ValueError('Truncated IPC metadata')
            message = struct.unpack_from('<I', metadata)[0]
            kind = field_offset(metadata, message, 1)
            if kind and metadata[kind] == 3:  # MessageHeader.RecordBatch
                header = field_offset(metadata, message, 2)
                batch = header + struct.unpack_from('<I', metadata, header)[0]
                length = field_offset(metadata, batch, 0)
                counts.append(struct.unpack_from('<q', metadata, length)[0] if length else 0)
            body = field_offset(metadata, message, 3)
            body_bytes = struct.unpack_from('<q', metadata, body)[0] if body else 0
            if body_bytes < 0:
                raise ValueError('Negative IPC body length')
            source.seek(body_bytes, 1)
    return counts


def main() -> None:
    config = json.loads((DATA_DIR / 'config/mbon-v1.json').read_text())
    paths = {role: DATA_DIR / '.cache' / spec['name'] for role, spec in config['files'].items()}
    annotations = feather.read_table(paths['annotations'])
    selected = annotations.filter(pc.equal(annotations[config['selection']['column']], config['selection']['equals']))
    counts = batch_row_counts(paths['connections'])
    with pa.memory_map(str(paths['connections']), 'r') as source:
        reader = ipc.open_file(source)
        if len(counts) != reader.num_record_batches:
            raise ValueError('IPC metadata batch count disagrees with PyArrow')
        connection_schema = reader.schema
    lines = ['# MaleCNS source schema', '', 'Generated by `uv run --project scripts/data python scripts/data/inspect_sources.py`.', '', '## Annotations', '', f'Rows: {annotations.num_rows:,}', '', '| Column | Arrow type |', '| --- | --- |']
    lines.extend(f'| {field.name} | {field.type} |' for field in annotations.schema)
    lines += ['', '## Connections', '', f'Record batches: {len(counts):,}', f'\nRows: {sum(counts):,}', '', 'Counts come from IPC record-batch metadata; column buffers are skipped without decoding.', '', '| Column | Arrow type |', '| --- | --- |']
    lines.extend(f'| {field.name} | {field.type} |' for field in connection_schema)
    lines += ['', '## MBON annotations', '', f'Neurons: {selected.num_rows}; cell types: {len(pc.unique(selected["type"]))}.']
    for column in ('type', 'somaSide'):
        lines += ['', f'| {column} | Neurons |', '| --- | --- |']
        values = pc.value_counts(selected[column]).to_pylist()
        lines.extend(f'| {row["values"]} | {row["counts"]} |' for row in sorted(values, key=lambda row: str(row['values'])))
    report = DATA_DIR / 'reports/source-schema.md'
    report.parent.mkdir(exist_ok=True)
    report.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    print(f'Annotations: {annotations.num_rows:,}; connections: {sum(counts):,} in {len(counts):,} batches; MBON: {selected.num_rows}')
    print(f'Wrote {report.relative_to(DATA_DIR.parent.parent)}')


if __name__ == '__main__':
    try:
        main()
    except (OSError, ValueError, struct.error) as error:
        sys.exit(f'Source inspection failed: {error}')
